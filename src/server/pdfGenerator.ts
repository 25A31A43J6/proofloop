/**
 * ProofLoop Minimal Pure TypeScript PDF Generator
 * Adheres strictly to PDF-1.4 specification (ISO 32000-1).
 * Generates standards-compliant, lightweight binary PDF buffers without external C-bindings.
 */

export interface PdfSection {
  heading?: string;
  lines: string[];
}

/**
 * Escapes characters for PDF literal strings in content streams.
 */
function escapePdfString(str: string): string {
  return str
    .replace(/\\/g, '\\\\')
    .replace(/\(/g, '\\(')
    .replace(/\)/g, '\\)');
}

/**
 * Wraps text into lines that fit within maxChars per line.
 */
function wrapText(text: string, maxChars = 78): string[] {
  const result: string[] = [];
  const rawLines = text.split('\n');

  for (const raw of rawLines) {
    if (raw.length <= maxChars) {
      result.push(raw);
      continue;
    }

    const words = raw.split(' ');
    let currentLine = '';

    for (const word of words) {
      if ((currentLine + (currentLine ? ' ' : '') + word).length > maxChars) {
        if (currentLine) result.push(currentLine);
        currentLine = word;
      } else {
        currentLine = currentLine ? `${currentLine} ${word}` : word;
      }
    }
    if (currentLine) {
      result.push(currentLine);
    }
  }

  return result;
}

/**
 * Generates a clean, valid PDF buffer for documents, resumes, and audit certificates.
 */
export function generatePdfDocument(options: {
  title: string;
  subtitle?: string;
  metadata?: Record<string, string>;
  sections: PdfSection[];
  footer?: string;
}): Buffer {
  const { title, subtitle, metadata, sections, footer } = options;

  // Stream content instructions (72 points = 1 inch, standard Letter = 612 x 792 pt)
  const streamOps: string[] = [];

  // Start text object
  streamOps.push('BT');

  // Title: Helvetica-Bold, 16pt at (54, 730)
  streamOps.push('/F2 16 Tf');
  streamOps.push('54 738 Td');
  streamOps.push(`(${escapePdfString(title)}) Tj`);

  let currentY = 738;

  // Subtitle
  if (subtitle) {
    currentY -= 18;
    streamOps.push('/F1 10 Tf');
    streamOps.push(`0 -18 Td`);
    streamOps.push(`(${escapePdfString(subtitle)}) Tj`);
  }

  // Metadata key-values
  if (metadata && Object.keys(metadata).length > 0) {
    currentY -= 14;
    streamOps.push('/F1 9 Tf');
    streamOps.push(`0 -14 Td`);
    const metaLine = Object.entries(metadata)
      .map(([k, v]) => `${k}: ${v}`)
      .join('  |  ');
    streamOps.push(`(${escapePdfString(metaLine)}) Tj`);
  }

  // Horizontal divider rule
  // We'll close text, stroke a line, and resume text
  streamOps.push('ET');
  currentY -= 12;
  streamOps.push('0.7 0.7 0.7 RG'); // gray color
  streamOps.push('0.75 w');
  streamOps.push(`54 ${currentY} m 558 ${currentY} l S`);
  streamOps.push('0 0 0 rg'); // black text

  streamOps.push('BT');
  streamOps.push(`54 ${currentY - 16} Td`);
  currentY -= 16;

  // Render sections
  for (const section of sections) {
    if (currentY < 90) break; // stay on single page margins

    if (section.heading) {
      currentY -= 16;
      streamOps.push('/F2 11 Tf');
      streamOps.push(`0 -16 Td`);
      streamOps.push(`(${escapePdfString(section.heading)}) Tj`);
    }

    streamOps.push('/F1 9.5 Tf');
    for (const rawLine of section.lines) {
      const wrapped = wrapText(rawLine, 82);
      for (const line of wrapped) {
        if (currentY < 75) break;
        currentY -= 13;
        streamOps.push(`0 -13 Td`);
        streamOps.push(`(${escapePdfString(line)}) Tj`);
      }
    }
  }

  // Footer at bottom
  const footerText =
    footer ||
    `Generated by ProofLoop Engine · Cryptographic Outcome Verification · ${new Date().toISOString().slice(0, 10)}`;
  streamOps.push('/F1 8 Tf');
  // Jump to footer position
  streamOps.push('ET');
  streamOps.push('BT');
  streamOps.push('54 42 Td');
  streamOps.push('0.4 0.4 0.4 rg'); // dark gray
  streamOps.push(`(${escapePdfString(footerText)}) Tj`);
  streamOps.push('ET');

  const streamData = streamOps.join('\n');
  const streamLength = Buffer.byteLength(streamData, 'utf-8');

  // Build standard PDF objects
  const objects: string[] = [];

  // Object 1: Catalog
  objects.push(`1 0 obj\n<<\n  /Type /Catalog\n  /Pages 2 0 R\n>>\nendobj`);

  // Object 2: Pages
  objects.push(`2 0 obj\n<<\n  /Type /Pages\n  /Kids [3 0 R]\n  /Count 1\n>>\nendobj`);

  // Object 3: Page (Letter 612 x 792)
  objects.push(`3 0 obj
<<
  /Type /Page
  /Parent 2 0 R
  /MediaBox [0 0 612 792]
  /Contents 4 0 R
  /Resources <<
    /Font <<
      /F1 5 0 R
      /F2 6 0 R
    >>
  >>
>>
endobj`);

  // Object 4: Content Stream
  objects.push(`4 0 obj
<<
  /Length ${streamLength}
>>
stream
${streamData}
endstream
endobj`);

  // Object 5: Standard Font Helvetica
  objects.push(`5 0 obj
<<
  /Type /Font
  /Subtype /Type1
  /BaseFont /Helvetica
>>
endobj`);

  // Object 6: Standard Font Helvetica-Bold
  objects.push(`6 0 obj
<<
  /Type /Font
  /Subtype /Type1
  /BaseFont /Helvetica-Bold
>>
endobj`);

  // Construct binary file with byte-exact cross reference table
  let pdf = `%PDF-1.4\n%\xE2\xE3\xCF\xD3\n`;
  const xrefOffsets: number[] = [0];

  for (let i = 0; i < objects.length; i++) {
    xrefOffsets.push(Buffer.byteLength(pdf, 'utf-8'));
    pdf += `${objects[i]}\n`;
  }

  const startXref = Buffer.byteLength(pdf, 'utf-8');
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;

  for (let i = 1; i <= objects.length; i++) {
    const offsetStr = String(xrefOffsets[i]).padStart(10, '0');
    pdf += `${offsetStr} 00000 n \n`;
  }

  pdf += `trailer
<<
  /Size ${objects.length + 1}
  /Root 1 0 R
>>
startxref
${startXref}
%%EOF\n`;

  return Buffer.from(pdf, 'utf-8');
}
